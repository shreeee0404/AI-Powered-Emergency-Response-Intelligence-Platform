def process_cyclone(file):

    print("\n====================================================")
    print("PROCESSING CYCLONE")
    print("====================================================")

    df = read_dataset(file)
    df = clean_columns(df)

    print("File:", file)
    print("Original records:", len(df))

    lat_col = find_column(
        df,
        [
            "LAT",
            "Lat",
            "Latitude",
            "latitude"
        ]
    )

    long_col = find_column(
        df,
        [
            "LON",
            "Lon",
            "Long",
            "Longitude",
            "longitude"
        ]
    )

    # Prefer wind speed as cyclone magnitude
    mag_col = find_column(
        df,
        [
            "USA_WIND",
            "WMO_WIND",
            "NEWDELHI_WIND",
            "BOM_WIND",
            "TOKYO_WIND"
        ]
    )

    if lat_col is None:
        raise ValueError(
            f"Latitude column not found in {file}"
        )

    if long_col is None:
        raise ValueError(
            f"Longitude column not found in {file}"
        )

    result = pd.DataFrame()

    result["Event_id"] = [
        "CY-" + str(i + 1)
        for i in range(len(df))
    ]

    result["Disaster_type"] = "Cyclone"

    result["Lat"] = extract_number(
        df[lat_col]
    )

    result["Long"] = extract_number(
        df[long_col]
    )

    if mag_col is not None:

        result["Magnitude"] = extract_number(
            df[mag_col]
        )

    else:

        result["Magnitude"] = np.nan

    # Cyclone severity
    result["Severity"] = np.select(
        [
            result["Magnitude"] >= 118,
            result["Magnitude"] >= 89,
            result["Magnitude"] >= 62
        ],
        [
            "High",
            "Medium",
            "Low"
        ],
        default="Low"
    )

    # India only
    result = filter_india(result)

    print("India records:", len(result))

    return result[
        [
            "Event_id",
            "Disaster_type",
            "Lat",
            "Long",
            "Magnitude",
            "Severity"
        ]
    ]


