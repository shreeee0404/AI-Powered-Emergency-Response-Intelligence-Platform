def read_dataset(file):

    extension = os.path.splitext(file)[1].lower()

    if extension == ".csv":

        try:
            df = pd.read_csv(
                file,
                low_memory=False
            )

        except UnicodeDecodeError:

            df = pd.read_csv(
                file,
                encoding="latin1",
                low_memory=False
            )

    elif extension in [".xlsx", ".xls"]:

        df = pd.read_excel(file)

    else:

        raise ValueError(
            f"Unsupported file format: {extension}"
        )

    return df


# ============================================================
# 3. CLEAN COLUMN NAMES
# ============================================================

def clean_columns(df):

    df.columns = (
        df.columns
        .astype(str)
        .str.strip()
        .str.replace("\ufeff", "", regex=False)
        .str.replace("<br>", " ", regex=False)
        .str.replace("\n", " ", regex=False)
        .str.replace(r"\s+", " ", regex=True)
    )

    return df


# ============================================================
# 4. FIND COLUMN AUTOMATICALLY
# ============================================================

def find_column(df, possible_names):

    # Exact match
    for name in possible_names:

        if name in df.columns:
            return name

    # Case-insensitive match
    column_map = {
        str(col).strip().lower(): col
        for col in df.columns
    }

    for name in possible_names:

        if name.lower() in column_map:
            return column_map[name.lower()]

    return None


# ============================================================
# 5. EXTRACT NUMERIC VALUES
# ============================================================

def extract_number(series):

    return pd.to_numeric(
        series
        .astype(str)
        .str.extract(
            r"([-+]?\d*\.?\d+)"
        )[0],
        errors="coerce"
    )


# ============================================================
# 6. INDIA FILTER
# ============================================================
#
# Approximate geographical limits of India:
#
# Latitude  : 6.5  to 37.5
# Longitude : 68.0 to 97.5
#
# Records outside these limits are removed.
# ============================================================

def filter_india(df):

    df = df.copy()

    df["Lat"] = pd.to_numeric(
        df["Lat"],
        errors="coerce"
    )

    df["Long"] = pd.to_numeric(
        df["Long"],
        errors="coerce"
    )

    # Remove missing coordinates
    df = df.dropna(
        subset=[
            "Lat",
            "Long"
        ]
    )

    india_mask = (
        (df["Lat"] >= 6.5) &
        (df["Lat"] <= 37.5) &
        (df["Long"] >= 68.0) &
        (df["Long"] <= 97.5)
    )

    df = df[india_mask].copy()

    return df


