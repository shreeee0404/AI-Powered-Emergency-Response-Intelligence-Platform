def prepare_file(file):
    raw = pd.read_csv(file, header=None)

    location_row = raw[
        raw.apply(
            lambda row: row.astype(str).str.contains("latitude", case=False, na=False).any(),
            axis=1
        )
    ]

    if location_row.empty:
        raise ValueError(f"Latitude information not found in {file}")

    location_index = location_row.index[0]

    latitude = pd.to_numeric(raw.iloc[location_index + 1, 0], errors="coerce")
    longitude = pd.to_numeric(raw.iloc[location_index + 1, 1], errors="coerce")

    header_row = raw[
        raw.apply(
            lambda row: row.astype(str).str.contains("time", case=False, na=False).any(),
            axis=1
        )
    ]

    if header_row.empty:
        raise ValueError(f"Time header not found in {file}")

    header_index = header_row.index[0]

    data = raw.iloc[header_index + 1:].copy()

    data = data.iloc[:, :2]

    data.columns = ["time", "value"]

    data["time"] = pd.to_datetime(data["time"], errors="coerce")

    data["value"] = pd.to_numeric(data["value"], errors="coerce")

    data = data.dropna(subset=["time"])

    data["latitude"] = latitude
    data["longitude"] = longitude

    return data[["time", "latitude", "longitude", "value"]]


