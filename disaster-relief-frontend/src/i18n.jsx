// ============================================================
// PER-USER LANGUAGE STORAGE
// The preference is scoped to the authenticated user so that
// changing language for one account never affects another.
// ============================================================

function getStoredUser() {
  try {
    return JSON.parse(localStorage.getItem("current_user") || "null")
  } catch {
    return null
  }
}

function getUserLanguageKey() {
  const user = getStoredUser()
  const identity = user?.id || user?.email
  return identity ? `${LANGUAGE_KEY}_${identity}` : LANGUAGE_KEY
}

