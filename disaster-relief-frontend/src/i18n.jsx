const LanguageContext = createContext(null)

function getInitialLanguage() {
  const stored =
    localStorage.getItem(getUserLanguageKey()) ||
    localStorage.getItem(LANGUAGE_KEY)

  if (stored && translations[stored]) return stored

  const user = getStoredUser()
  if (user?.language && translations[user.language]) {
    return user.language
  }

  return "en"
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(getInitialLanguage)

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = "ltr"
  }, [language])

  const setLanguage = (nextLanguage) => {
    if (!translations[nextLanguage]) return

    localStorage.setItem(getUserLanguageKey(), nextLanguage)
    localStorage.setItem(LANGUAGE_KEY, nextLanguage)

    const storedUser = getStoredUser()
    if (storedUser && typeof storedUser === "object") {
      localStorage.setItem(
        "current_user",
        JSON.stringify({ ...storedUser, language: nextLanguage })
      )
    }

    setLanguageState(nextLanguage)
    document.documentElement.lang = nextLanguage
  }

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      languages: supportedLanguages,
      t: (key, params) => {
        if (key === undefined || key === null) return ""

        const template =
          translations[language]?.[key] ??
          translations.en[key] ??
          key

        if (!params || typeof template !== "string") {
          return template
        }

        return template.replace(
          /\{\{(\w+)\}\}/g,
          (match, token) =>
            params[token] !== undefined ? params[token] : match
        )
      },
    }),
    [language]
  )

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error("useLanguage must be used inside LanguageProvider")
  }
  return context
}

export function translateStatus(t, status) {
  const normalized = String(status || "")
    .trim()
    .toLowerCase()
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")

  const statusKey = statusTranslationKeys[normalized]

  if (statusKey) {
    return t(statusKey)
  }

  return String(status || "")
}

